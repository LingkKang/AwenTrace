import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
import { reconstructText } from '../../src/index.js';
import type { Trace } from '../../src/index.js';
import { gunzipSync } from 'node:zlib';

async function downloadText(page: Page, format: string) {
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: `Download ${format.toUpperCase()}${format === 'jsonl' ? ' gzip' : ''}`, exact: true }).click();
  const download = await pending;
  expect(download.suggestedFilename()).toMatch(new RegExp(`^awentrace-.+\\.${format}${format === 'jsonl' ? '\\.gz' : ''}$`));
  const stream = await download.createReadStream();
  if (!stream) throw new Error('Download stream unavailable');
  const chunks: Buffer[] = [];
  for await (const chunk of stream) chunks.push(Buffer.from(chunk));
  expect(await download.failure()).toBeNull();
  const bytes = Buffer.concat(chunks);
  if (format === 'jsonl') expect([...bytes.subarray(0, 2)]).toEqual([31, 139]);
  return (format === 'jsonl' ? gunzipSync(bytes) : bytes).toString('utf8');
}

test.beforeEach(async ({ page }) => { await page.goto('./'); });

test('start, pause, resume and reset preserve or clear the appropriate state', async ({ page }, testInfo) => {
  const writer = page.getByRole('textbox', { name: 'Writing', exact: true });
  const download = page.getByRole('button', { name: 'Download JSON', exact: true });
  await expect(writer).toHaveJSProperty('readOnly', true);
  await expect(download).toBeDisabled();
  await expect(page.locator('h1 small')).toHaveText('dev build');
  await expect(page.getByRole('link', { name: 'https://github.com/LingkKang/AwenTrace', exact: true })).toHaveAttribute('href', 'https://github.com/LingkKang/AwenTrace');
  await expect(page.locator('#replay-text')).toHaveClass('placeholder');
  await expect(page.locator('#replay-text')).toHaveText('(empty text)');
  await page.getByRole('button', { name: 'Start a session', exact: true }).click();
  await writer.click();
  const bounds = (await writer.boundingBox())!;
  await page.mouse.move(bounds.x + 30, bounds.y + 30, { steps: 4 });
  await writer.pressSequentially('One  two');
  await page.keyboard.press('Enter');
  await page.keyboard.insertText('three\tfour');
  await expect(page.locator('#text-count')).toHaveText('19 characters · 4 words');
  await page.getByRole('button', { name: 'Pause recording', exact: true }).click();
  await expect(page.getByRole('status', { name: 'Recording status' })).toHaveText('Paused');
  await expect(writer).toHaveJSProperty('readOnly', true);
  const paused: Trace = JSON.parse(await downloadText(page, 'json'));
  expect(paused.stopped).toBe(false);
  expect(paused.header.capturePointerMoves).toBe(false);
  expect(paused.events.some(event => event.kind === 'mousemove' || event.kind === 'pointermove')).toBe(false);
  expect(paused.events.some(event => event.kind === 'click')).toBe(true);
  expect(paused.events.at(-1)?.kind).toBe('pause');
  await writer.click();
  await page.keyboard.type('ignored');
  await expect(writer).toHaveValue('One  two\nthree\tfour');
  expect(JSON.parse(await downloadText(page, 'json'))).toEqual(paused);
  await page.locator('#replay').focus();
  await page.keyboard.press('Home');
  await expect(page.locator('#replay-index')).toHaveText('0');
  await expect(page.locator('#replay-text')).toHaveClass('placeholder');
  await expect(page.locator('#replay-text')).toHaveText('(empty text)');
  await page.keyboard.press('End');
  await expect(page.locator('#replay-text')).not.toHaveClass('placeholder');
  await page.getByRole('button', { name: 'Resume the session', exact: true }).click();
  await writer.press('End');
  await writer.pressSequentially(' more');
  const resumed: Trace = JSON.parse(await downloadText(page, 'json'));
  expect(resumed.header.sessionId).toBe(paused.header.sessionId);
  expect(reconstructText(resumed)).toBe('One  two\nthree\tfour more');
  expect(resumed.events.filter(event => event.kind === 'pause')).toHaveLength(1);
  expect(resumed.events.filter(event => event.kind === 'resume')).toHaveLength(1);
  await expect(page.getByRole('button', { name: 'Reset', exact: true })).toHaveAttribute('title', /clear all records/);
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  await expect(writer).toHaveValue('');
  await expect(writer).toHaveJSProperty('readOnly', true);
  await expect(download).toBeDisabled();
  await expect(page.getByRole('status', { name: 'Recording status' })).toHaveText('Ready');
  await expect(page.locator('#event-count')).toHaveText('0');
  await expect(page.locator('#text-count')).toHaveText('0 characters · 0 words');
  await expect(page.locator('#events')).toHaveText('No records yet.');
  await expect(page.locator('#replay')).toBeDisabled();
  await expect(page.locator('#replay-index')).toHaveText('0');
  await expect(page.locator('#replay-text')).toHaveClass('placeholder');
  await expect(page.getByRole('button', { name: 'Download JSONL gzip', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Download CSV', exact: true })).toBeDisabled();
  await page.screenshot({ path: testInfo.outputPath('demo-ready.png'), fullPage: true });
  await page.getByRole('button', { name: 'Start a session', exact: true }).click();
  await writer.pressSequentially('Fresh start.');
  const next: Trace = JSON.parse(await downloadText(page, 'json'));
  expect(next.header.sessionId).not.toBe(paused.header.sessionId);
  expect(next.header.initialText).toBe('');
  expect(reconstructText(next)).toBe('Fresh start.');
  expect(JSON.stringify(next)).not.toContain('three');
});

test('latest 200 records, text history and downloads retain the complete paused session', async ({ page }, testInfo) => {
  await page.getByRole('button', { name: 'Start a session', exact: true }).click();
  const text = 'word '.repeat(50);
  await page.getByRole('textbox', { name: 'Writing', exact: true }).pressSequentially(text);
  await page.getByRole('button', { name: 'Pause recording', exact: true }).click();
  const trace: Trace = JSON.parse(await downloadText(page, 'json'));
  expect(reconstructText(trace)).toBe(text);
  expect(trace.events.length).toBeGreaterThan(200);
  await expect(page.locator('#events tr')).toHaveCount(200);
  await expect(page.locator('#events tr').first().locator('td').first()).toHaveText(String(trace.events.length));
  await expect(page.locator('#events tr').last().locator('td').first()).toHaveText(String(trace.events.length - 199));
  await expect(page.locator('#event-count')).toHaveText(String(trace.events.length));
  await expect(page.locator('#text-count')).toHaveText('250 characters · 50 words');
  await expect(page.locator('#replay-text')).toHaveText(text);
  const lines = (await downloadText(page, 'jsonl')).trim().split('\n').map(line => JSON.parse(line));
  expect(lines[0]).toEqual({ record: 'header', ...trace.header });
  expect(lines.slice(1, -1)).toEqual(trace.events.map(event => ({ record: 'event', ...event })));
  expect(lines.at(-1)).toEqual({ record: 'footer', finalText: trace.finalText, stopped: false });
  const csv = (await downloadText(page, 'csv')).trim().split('\r\n');
  expect(csv).toHaveLength(trace.events.length + 1);
  expect(csv.at(-1)).toContain('"pause"');
  await page.screenshot({ path: testInfo.outputPath('demo-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('demo-mobile.png'), fullPage: true });
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  await expect(page.locator('#event-count')).toHaveText('0');
  await expect(page.getByRole('button', { name: 'Start a session', exact: true })).toBeVisible();
});
